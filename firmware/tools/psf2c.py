#!/usr/bin/env python3
"""Convert a PSF1/PSF2 console font (optionally gzipped) to a C bitmap font.

Output covers Unicode codepoints 0x20..0xFF (ASCII + Latin-1). Glyphs are
stored row-major, one byte per row, MSB = leftmost pixel, 8 px wide.
"""
import gzip, struct, sys

def load(path):
    data = open(path, 'rb').read()
    if data[:2] == b'\x1f\x8b':
        data = gzip.decompress(data)
    if data[:2] == b'\x36\x04':  # PSF1
        mode, h = data[2], data[3]
        n = 512 if mode & 1 else 256
        w = 8
        glyphs = [data[4 + i*h: 4 + (i+1)*h] for i in range(n)]
        table = None
        if mode & 0x06:
            table = {}
            pos = 4 + n*h
            for i in range(n):
                while True:
                    cp = struct.unpack_from('<H', data, pos)[0]; pos += 2
                    if cp == 0xFFFF: break
                    if cp == 0xFFFE:  # sequence; skip to terminator
                        while struct.unpack_from('<H', data, pos)[0] != 0xFFFF: pos += 2
                        continue
                    table.setdefault(cp, i)
        return w, h, glyphs, table
    if data[:4] == b'\x72\xb5\x4a\x86':  # PSF2
        (ver, hdr, flags, n, cs, h, w) = struct.unpack_from('<7I', data, 4)
        glyphs = [data[hdr + i*cs: hdr + (i+1)*cs] for i in range(n)]
        table = None
        if flags & 1:
            table = {}
            pos = hdr + n*cs
            for i in range(n):
                buf = b''
                while data[pos] != 0xFF:
                    if data[pos] == 0xFE:
                        pos += 1
                        while data[pos] not in (0xFE, 0xFF): pos += 1
                        continue
                    buf += bytes([data[pos]]); pos += 1
                pos += 1
                for ch in buf.decode('utf-8', 'replace'):
                    table.setdefault(ord(ch), i)
        return w, h, glyphs, table
    raise SystemExit('not a PSF font')

def main():
    path, out = sys.argv[1], sys.argv[2]
    w, h, glyphs, table = load(path)
    assert w == 8, 'only 8px wide fonts supported'
    if table is None:
        table = {i: i for i in range(len(glyphs))}
    missing = []
    rows = []
    for cp in range(0x20, 0x100):
        gi = table.get(cp)
        if gi is None:
            missing.append(cp); gi = table.get(0x3F, 0x3F)  # '?'
        rows.append((cp, glyphs[gi]))
    with open(out, 'w') as f:
        f.write('/* Generated by tools/psf2c.py from %s. Do not edit. */\n' % path.split('/')[-1])
        f.write('#include "font8x16.h"\n\n')
        f.write('const uint8_t font8x16_glyphs[FONT8X16_COUNT][FONT8X16_HEIGHT] = {\n')
        for cp, g in rows:
            label = chr(cp) if 0x20 <= cp < 0x7F and cp not in (0x5C, 0x2A, 0x2F) else ''
            f.write('    /* U+%04X %s */ {%s},\n' % (cp, label, ', '.join('0x%02X' % b for b in g)))
        f.write('};\n')
    print('font %dx%d, %d glyphs, missing Latin-1 codepoints: %s' % (w, h, len(glyphs), ' '.join('%04X' % c for c in missing) or 'none'))

main()
